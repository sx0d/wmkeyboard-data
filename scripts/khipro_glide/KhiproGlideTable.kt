// Writes data/bn/bn_khipro_glide.txt.gz: the Khipro spellings of every word of
// data/bn/bn_full.txt.gz, which WM Keyboard reads to glide on its Khipro
// layout instead of working them out on the phone (minutes of every core).
// Built by scripts/build_bn_khipro_glide.sh against WM Keyboard's own
// KhiproRomanizer, so the spellings are exactly the ones the app would make.
import com.wasimaster.wmkeyboard.core.transliteration.KhiproRomanizer
import java.io.File
import java.util.zip.GZIPInputStream
import java.util.zip.GZIPOutputStream
import java.util.concurrent.Executors
import java.util.concurrent.Callable

fun main(args: Array<String>) {
    val words = GZIPInputStream(File(args[0]).inputStream()).bufferedReader().readLines()
        .map { it.trim().split(Regex("\\s+"))[0] }.filter { it.isNotEmpty() && !it.startsWith("#") }.distinct()
    KhiproRomanizer.warm()
    val pool = Executors.newFixedThreadPool(Runtime.getRuntime().availableProcessors())
    val parts = pool.invokeAll(words.chunked(2000).map { chunk -> Callable {
        chunk.mapNotNull { w -> KhiproRomanizer.spellings(w).takeIf { it.isNotEmpty() }?.let { w + "\t" + it.joinToString("\t") } }
    } }).flatMap { it.get() }
    pool.shutdown()
    GZIPOutputStream(File(args[1]).outputStream()).bufferedWriter().use { out ->
        out.write("# Khipro spellings of bn_full.txt.gz, for gliding on WM Keyboard's Khipro layout.\n")
        out.write("# word<TAB>spelling[<TAB>spelling...]; generated by scripts/build_bn_khipro_glide.sh.\n")
        parts.forEach { out.write(it); out.write("\n") }
    }
    System.err.println("${words.size} words, ${parts.size} spelled")
}
